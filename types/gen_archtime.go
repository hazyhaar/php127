//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
)

func djbx33aHash(text string) uint64 {
	h := uint64(5381)
	for i := 0; i < len(text); i++ {
		h = ((h << 5) + h) + uint64(text[i])
	}
	return h | (1 << 63)
}

func main() {
	var entries []string
	for i := 0; i < 256; i++ {
		entries = append(entries, string([]byte{byte(i)}))
	}
	entries = append(entries, "")
	fundamentals := []string{
		"NULL", "boolean", "integer", "double", "string", "array", "object", "resource",
		"stdClass", "true", "false",
	}
	entries = append(entries, fundamentals...)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen_archtime.go; DO NOT EDIT.\n\n")
	buf.WriteString("package types\n\n")
	buf.WriteString("type archtimeInternedEntry struct {\n")
	buf.WriteString("\ttext   string\n")
	buf.WriteString("\toffset uint32\n")
	buf.WriteString("\tcap    uint32\n")
	buf.WriteString("\thash   uint64\n")
	buf.WriteString("}\n\n")

	var offset uint32
	var byteVals [256]string
	var emptyVal string
	fundamentalVals := make(map[string]string)

	buf.WriteString("var archtimeInternedTable = [...]archtimeInternedEntry{\n")
	for idx, text := range entries {
		length := uint32(len(text))
		capacity := (length + 1 + 7) &^ 7
		hash := djbx33aHash(text)
		fmt.Fprintf(&buf, "\t{text: %q, offset: %d, cap: %d, hash: 0x%016x},\n", text, offset, capacity, hash)
		valExpr := fmt.Sprintf("Value{Type: TypeString, Flags: FlagImmutable | FlagInterned, DataSlot: %d, Scalar: %d}", offset, length)
		if idx < 256 {
			byteVals[idx] = valExpr
		} else if idx == 256 {
			emptyVal = valExpr
		} else {
			fundamentalVals[text] = valExpr
		}
		offset += 24 + capacity
	}
	buf.WriteString("}\n\n")

	fmt.Fprintf(&buf, "const archtimeProcessZoneBytes uint32 = %d\n\n", offset)
	fmt.Fprintf(&buf, "var emptyString = %s\n\n", emptyVal)

	buf.WriteString("var byteTable = [256]Value{\n")
	for i := 0; i < 256; i++ {
		fmt.Fprintf(&buf, "\t%s,\n", byteVals[i])
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var (\n")
	fmt.Fprintf(&buf, "\tInternedEmpty    = %s\n", emptyVal)
	fmt.Fprintf(&buf, "\tInternedZero     = %s\n", byteVals['0'])
	fmt.Fprintf(&buf, "\tInternedOne      = %s\n", byteVals['1'])
	fmt.Fprintf(&buf, "\tInternedNull     = %s\n", fundamentalVals["NULL"])
	fmt.Fprintf(&buf, "\tInternedBoolean  = %s\n", fundamentalVals["boolean"])
	fmt.Fprintf(&buf, "\tInternedInteger  = %s\n", fundamentalVals["integer"])
	fmt.Fprintf(&buf, "\tInternedDouble   = %s\n", fundamentalVals["double"])
	fmt.Fprintf(&buf, "\tInternedString   = %s\n", fundamentalVals["string"])
	fmt.Fprintf(&buf, "\tInternedArray    = %s\n", fundamentalVals["array"])
	fmt.Fprintf(&buf, "\tInternedObject   = %s\n", fundamentalVals["object"])
	fmt.Fprintf(&buf, "\tInternedResource = %s\n", fundamentalVals["resource"])
	fmt.Fprintf(&buf, "\tInternedStdClass = %s\n", fundamentalVals["stdClass"])
	fmt.Fprintf(&buf, "\tInternedTrue     = %s\n", fundamentalVals["true"])
	fmt.Fprintf(&buf, "\tInternedFalse    = %s\n", fundamentalVals["false"])
	buf.WriteString(")\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("archtime_interned_gen.go", formatted, 0o644); err != nil {
		panic(err)
	}
}
